import { BaseEntity, Instant } from '../common/types';
import { CertificateKind } from '../domain/certificate.model';

/**
 * Data Transfer Object for a certificate.
 * Represents a certificate with its metadata, public key, and expiry information.
 */
export interface CertificateDTO extends BaseEntity {
  /**
   * The name of the certificate.
   * @example "Server SSL Certificate"
   */
  name: string;

  /**
   * A description of the certificate's purpose or usage.
   * @example "SSL certificate for securing server communications"
   */
  description: string;

  /**
   * The public key of the certificate in PEM format.
   * @example "-----BEGIN PUBLIC KEY-----\nMIIBIjANBgkqhkiG9w0BAQEFAAOCAQ8AMIIBCgKCAQEA..."
   */
  publicKey: string;

  /**
   * The certificate in PEM format.
   * @example "-----BEGIN CERTIFICATE-----\nMIIDXTCCAkWgAwIBAgIJAKoK/heBjcOuMA0GCSqGSIb3DQEBBQUAMEUx..."
   */
  certificate: string;

  /**
   * The expiry date and time of the certificate in ISO 8601 format.
   * @example "2026-01-01T00:00:00.000Z"
   */
  expiry: Instant;

  /**
   * The PEM bundle of intermediate/root CA certificates supplied when importing an externally-issued
   * certificate. Null for self-signed certificates generated by OIBus.
   * @example "-----BEGIN CERTIFICATE-----\nMIIDXTCCAkWgAwIBAgIJAKoK/heBjcOuMA0GCSqGSIb3DQEBBQUAMEUx...\n-----END CERTIFICATE-----"
   */
  certificateChain: string | null;

  /**
   * Whether OIBus presents the certificate, with its private key (`key-pair`), or trusts it to validate the certificate of a
   * server (`trusted`, without private key).
   */
  kind: CertificateKind;

  /**
   * Whether the certificate is a certification authority (its basic constraints allow it to issue certificates): a trusted
   * certification authority validates the certificates it issued, a trusted server certificate only itself.
   * @example false
   */
  certificationAuthority: boolean;

  /**
   * The SHA-256 fingerprint of the certificate, to compare with the one shown by the server or its administrator.
   * @example "C3:5D:A2:4A:30:F6:52:27:1F:C4:30:16:79:99:DD:60:8A:D4:43:9C:EA:12:94:D7:F4:88:63:CE:A4:73:B6:1A"
   */
  fingerprint: string;
}

/**
 * Command DTO for creating or updating a certificate.
 * Used as the request body for certificate creation/update endpoints.
 */
export interface CertificateCommandDTO {
  /**
   * The name of the certificate.
   * @example "New Server SSL Certificate"
   */
  name: string;

  /**
   * A description of the certificate's purpose or usage.
   * @example "New SSL certificate for securing server communications"
   */
  description: string;

  /**
   * Whether to regenerate the certificate.
   * @example false
   */
  regenerateCertificate: boolean;

  /**
   * Options for generating the certificate.
   * Set to `null` to not regenerate certificate
   */
  options: CertificateOptions | null;
}

/**
 * Options for generating a certificate.
 * Used to specify details for certificate generation.
 */
export interface CertificateOptions {
  /**
   * The common name (e.g., domain name) for the certificate.
   * @example "example.com"
   */
  commonName: string;

  /**
   * The country name for the certificate.
   * @example "FR"
   */
  countryName: string;

  /**
   * The state or province name for the certificate.
   * @example "Savoie"
   */
  stateOrProvinceName: string;

  /**
   * The locality (e.g., city) name for the certificate.
   * @example "Chambéry"
   */
  localityName: string;

  /**
   * The organization name for the certificate.
   * @example "Example Inc."
   */
  organizationName: string;

  /**
   * The key size in bits for the certificate.
   * @example 2048
   */
  keySize: number;

  /**
   * The number of days before the certificate expires.
   * @example 365
   */
  daysBeforeExpiry: number;
}

export const ALL_CERTIFICATE_EXPORT_FORMATS = ['PEM', 'DER'] as const;
export type CertificateExportFormat = (typeof ALL_CERTIFICATE_EXPORT_FORMATS)[number];

/**
 * Command DTO for exporting a certificate's private key.
 * Used as the request body for the private key export endpoint, to protect the exported key at rest.
 */
export interface CertificatePrivateKeyExportCommandDTO {
  /**
   * The passphrase used to encrypt the exported private key.
   * @example "S3cr3tPassphrase!"
   */
  passphrase: string;
}
